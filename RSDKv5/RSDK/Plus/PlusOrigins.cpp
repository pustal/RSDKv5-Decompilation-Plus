/** A file's key combined with an AFS2 subkey, as CRIWARE does. */
uint64 KeyWithSubkey(uint64 key, uint16 subkey)
{
    if (!subkey)
        return key;
    return key * (((uint64)subkey << 16) | (uint16)(~subkey + 2));
}

/** A clHCA decoder, freed when it goes out of scope. */
struct HcaDecoder {
    clHCA *hca = clHCA_new();
    ~HcaDecoder() { clHCA_delete(hca); }
    HcaDecoder()                              = default;
    HcaDecoder(const HcaDecoder &)            = delete;
    HcaDecoder &operator=(const HcaDecoder &) = delete;
};

/** Reads @p hca's header into @p decoder with @p key. */
bool ReadHcaHeader(clHCA *decoder, const std::vector<uint8> &hca, uint64 key, clHCA_stInfo *info)
{
    const int32 headerSize = clHCA_isOurFile(hca.data(), (unsigned int)hca.size());
    if (headerSize <= 0 || (size_t)headerSize > hca.size() || clHCA_DecodeHeader(decoder, hca.data(), (unsigned int)headerSize) < 0)
        return false;
    clHCA_SetKey(decoder, key);
    return clHCA_getInfo(decoder, info) >= 0 && info->blockSize && info->headerSize + (uint64)info->blockSize * info->blockCount <= hca.size();
}

/**
 * How well @p key decodes @p hca: the failures among a few blocks spread over
 * the file (a wrong key makes nearly every block fail).
 */
int32 KeyFailures(const std::vector<uint8> &hca, uint64 key)
{
    HcaDecoder decoder;
    clHCA_stInfo info;
    if (!ReadHcaHeader(decoder.hca, hca, key, &info))
        return 1 << 20;
    const uint32 tests = info.blockCount < 8 ? info.blockCount : 8;
    int32 failures     = 0;
    std::vector<uint8> block(info.blockSize);
    for (uint32 t = 0; t < tests; ++t) {
        const uint32 index = (uint32)((uint64)info.blockCount * (2 * t + 1) / (2 * tests));
        memcpy(block.data(), hca.data() + info.headerSize + (size_t)index * info.blockSize, info.blockSize);
        if (clHCA_TestBlock(decoder.hca, block.data(), info.blockSize) < 0)
            ++failures;
    }
    return failures;
}

/** Bytes an HCA header chunk takes, from its (unmasked) name; 0 for the padding that ends the header. */
uint32 HcaChunkSize(const char name[4], const std::vector<uint8> &hca, size_t at)
{
    if (!memcmp(name, "fmt\0", 4) || !memcmp(name, "comp", 4) || !memcmp(name, "loop", 4))
        return 16;
    if (!memcmp(name, "dec\0", 4))
        return 12;
    if (!memcmp(name, "vbr\0", 4) || !memcmp(name, "rva\0", 4))
        return 8;
    if (!memcmp(name, "ath\0", 4) || !memcmp(name, "ciph", 4))
        return 6;
    if (!memcmp(name, "comm", 4))
        return at + 4 < hca.size() ? 5 + hca[at + 4] : 0;
    return 0;
}

/**
 * Rewrites @p hca without its encryption: every block decrypted (with a new
 * checksum), and the header's cipher set to none (with a new checksum).
 */
bool MakeKeylessHca(std::vector<uint8> &hca, uint64 key)
{
    HcaDecoder decoder;
    clHCA_stInfo info;
    if (!ReadHcaHeader(decoder.hca, hca, key, &info))
        return false;
    if (!info.encryptionEnabled)
        return true;

    for (uint32 b = 0; b < info.blockCount; ++b) {
        if (clHCA_DecryptBlock(decoder.hca, hca.data() + info.headerSize + (size_t)b * info.blockSize, info.blockSize) < 0)
            return false;
    }

    // The header's chunks follow "HCA\0", u16 version, u16 header size; names
    // may be masked (their top bits set), which clHCA accepts either way.
    bool found = false;
    for (size_t at = 8; at + 4 <= info.headerSize - 2;) {
        char name[4];
        for (int32 i = 0; i < 4; ++i) name[i] = (char)(hca[at + i] & 0x7F);
        if (!memcmp(name, "ciph", 4)) {
            hca[at + 4] = 0; // u16 cipher type: 0, none.
            hca[at + 5] = 0;
            found       = true;
            break;
        }
        const uint32 size = HcaChunkSize(name, hca, at);
        if (!size)
            break;
        at += size;
    }
    if (!found)
        return false;
    const uint16 sum             = clHCA_Checksum(hca.data(), info.headerSize - 2);
    hca[info.headerSize - 2]     = (uint8)(sum >> 8);
    hca[info.headerSize - 1]     = (uint8)sum;

    // It must now read as an unencrypted file.
    HcaDecoder check;
    clHCA_stInfo after;
    return ReadHcaHeader(check.hca, hca, 0, &after) && !after.encryptionEnabled;
}

