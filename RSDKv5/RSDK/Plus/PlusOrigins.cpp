/** What the conversion is doing, shared between its thread and the engine's. */
struct OriginsAudioJob {
    std::mutex lock;
    std::thread worker;
    std::atomic<bool> running{ false };
    std::atomic<bool> cancel{ false };
    std::atomic<int32> percent{ 0 };
    std::atomic<bool> finished{ false }; ///< Done since the engine last looked (OriginsAudioFinished()).
    std::string message;                 ///< Under lock.
};

OriginsAudioJob originsJob;

void SetOriginsMessage(const std::string &text)
{
    std::lock_guard<std::mutex> guard(originsJob.lock);
    originsJob.message = text;
    PrintLog(PRINT_NORMAL, "[Plus] Sonic Origins audio: %s", text.c_str());
}

/** The retro folders: the user folder's, then those added with AddPackFolder(). */
std::vector<std::string> RetroFolders()
{
    std::vector<std::string> folders = { UserPath(std::string(kRetroFolder) + "/") };
    folders.insert(folders.end(), extraPackFolders.begin(), extraPackFolders.end());
    return folders;
}

bool UserFileExists(const std::string &path)
{
    PackFile file(path, "rb");
    return file.file != nullptr;
}

/**
 * Where Sonic Origins' file @p fileName ("STH1_music.acb") is: in the
 * "origins" folder of the first retro folder that has it (the files may be
 * spread over the TV and a USB drive, say).
 *
 * @param retroFolder Receives that retro folder (full path, trailing slash).
 * @return Its full path, or "" when no folder has it.
 */
std::string FindOriginsFile(const std::string &fileName, std::string *retroFolder)
{
    for (const std::string &retro : RetroFolders()) {
        const std::string path = retro + kOriginsAudioFolder + "/" + fileName;
        if (UserFileExists(path)) {
            if (retroFolder)
                *retroFolder = retro;
            return path;
        }
    }
    return "";
}

/** One file to write in a game's pack: where its audio is and the names it goes under. */
struct PlannedWave {
    const AcbFile *acb = nullptr;
    AcbWave wave;
    std::vector<std::string> paths;
    uint64 offset = 0;
    uint32 size   = 0;
};

bool WriteOriginsPack(const std::string &path, const OriginsGame &game, std::vector<PlannedWave> &plan, size_t entries, uint64 *done,
                      uint64 total, std::string *error);

/**
 * Writes @p game's pack, next to the "origins" folder its first file was
 * found in. @p done and @p total count bytes over all games, for the progress.
 *
 * @return False with a reason in @p error ("no files" when the game has
 *         none); true (with the @p written names) otherwise.
 */
bool ConvertOriginsGame(const OriginsGame &game, uint64 *done, uint64 total, int32 *written, std::string *error)
{
    // The game's files that are there.
    std::map<std::string, std::unique_ptr<AcbFile>> files;
    std::string outputFolder;
    bool ownFiles = false; // Shared files alone (HITE_sfx, Sonic 1's music for Sonic 2) make no pack.
    for (const char *name : game.files) {
        const OriginsAudioFile *info = FindOriginsAudioFile(name);
        std::string folder;
        const std::string acbPath = info ? FindOriginsFile(std::string(name) + ".acb", &folder) : std::string();
        if (acbPath.empty())
            continue;
        const std::string awbPath = info->streamed ? FindOriginsFile(std::string(name) + ".awb", nullptr) : std::string();
        if (info->streamed && awbPath.empty()) {
            *error = std::string(name) + ".awb is missing (it goes with " + name + ".acb)";
            return false;
        }
        std::unique_ptr<AcbFile> acb(new AcbFile());
        if (!acb->Open(acbPath, awbPath, info->key)) {
            *error = std::string(name) + (info->streamed ? ".acb or its .awb" : ".acb") + " could not be read";
            return false;
        }
        if (outputFolder.empty())
            outputFolder = folder;
        ownFiles    = ownFiles || name == game.files[0] || name == game.files[1];
        files[name] = std::move(acb);
    }
    if (!ownFiles) {
        *error = "no files";
        return false;
    }

    // Each sound the game asks for, found in the first file that has its cue;
    // names playing the same audio share it.
    std::vector<PlannedWave> plan;
    std::map<std::pair<const AcbFile *, std::pair<bool, uint32>>, size_t> byWave;
    for (size_t s = 0; s < game.count; ++s) {
        const OriginsSound &sound = game.sounds[s];
        for (const char *name : game.files) {
            auto file = files.find(name);
            AcbWave wave;
            if (file == files.end() || !file->second->FindCue(sound.cue, &wave))
                continue;
            const std::string path = sound.music ? std::string("Data/Music/") + sound.path : std::string("Data/SoundFX/") + sound.path + ".wav";
            const auto key         = std::make_pair(file->second.get(), std::make_pair(wave.streamed, wave.id));
            auto known             = byWave.find(key);
            if (known == byWave.end()) {
                byWave[key] = plan.size();
                PlannedWave planned;
                planned.acb  = file->second.get();
                planned.wave = wave;
                planned.paths.push_back(path);
                plan.push_back(planned);
            }
            else {
                plan[known->second].paths.push_back(path);
            }
            break;
        }
    }
    size_t entries = 0;
    for (const PlannedWave &planned : plan) entries += planned.paths.size();
    if (!entries || entries > kMaxPackFiles) {
        *error = "none of its sounds were found";
        return false;
    }

    // Written under a temporary name, then renamed over the old pack, which a
    // running game may be reading. Android's picked folder cannot rename: the
    // pack is written in place there. Either way its signature is written
    // last, so an interrupted pack is never taken for a pack.
    const std::string finalPath = outputFolder + OriginsAudioPackName(game.id);
#if RETRO_PLATFORM == RETRO_ANDROID
    const std::string path = finalPath;
#else
    const std::string path = finalPath + ".part";
#endif
    const bool ok = WriteOriginsPack(path, game, plan, entries, done, total, error);
#if RETRO_PLATFORM != RETRO_ANDROID
    if (!ok) {
        remove(path.c_str());
        return false;
    }
    remove(finalPath.c_str()); // Windows' rename() does not replace.
    if (rename(path.c_str(), finalPath.c_str()) != 0) {
        *error = "cannot rename " + OriginsAudioPackName(game.id) + ".part";
        remove(path.c_str());
        return false;
    }
#else
    if (!ok)
        return false;
#endif
    *written = (int32)entries;
    return true;
}

/** Writes the pack of @p plan (@p entries names) to @p path; see ConvertOriginsGame(). */
bool WriteOriginsPack(const std::string &path, const OriginsGame &game, std::vector<PlannedWave> &plan, size_t entries, uint64 *done,
                      uint64 total, std::string *error)
{
    std::vector<uint8> table(8 + entries * 24, 0);
    {
        PackFile out(path, "wb");
        if (!out.file || fwrite(table.data(), 1, table.size(), out.file) != table.size()) {
            *error = "cannot write " + OriginsAudioPackName(game.id);
            return false;
        }

        std::map<std::pair<const AcbFile *, uint16>, bool> useSubkey; // Found once per list.
        uint64 offset = table.size();
        std::vector<uint8> hca;
        for (PlannedWave &planned : plan) {
            if (originsJob.cancel) {
                *error = "cancelled";
                return false;
            }
            if (!planned.acb->ReadWave(planned.wave, &hca)) {
                *error = "damaged file";
                return false;
            }
            const uint16 subkey = planned.acb->Subkey(planned.wave);
            const auto list     = std::make_pair(planned.acb, subkey);
            if (!useSubkey.count(list))
                useSubkey[list] = subkey && KeyFailures(hca, KeyWithSubkey(planned.acb->Key(), subkey)) < KeyFailures(hca, planned.acb->Key());
            const uint64 key = useSubkey[list] ? KeyWithSubkey(planned.acb->Key(), subkey) : planned.acb->Key();
            if (!MakeKeylessHca(hca, key)) {
                *error = "a sound could not be decrypted (not Sonic Origins' files?)";
                return false;
            }
            if (offset + hca.size() > 0x7FFFFFFFull) {
                *error = "the pack would be too big";
                return false;
            }
            if (fwrite(hca.data(), 1, hca.size(), out.file) != hca.size()) {
                *error = "cannot write " + OriginsAudioPackName(game.id) + " (disk full?)";
                return false;
            }
            planned.offset = offset;
            planned.size   = (uint32)hca.size();
            offset += hca.size();

            *done += planned.acb->WaveSize(planned.wave);
            // Sonic 1's music counts twice (Sonic 2 shares three jingles): never 100% before the end.
            const uint64 percent = total ? *done * 100 / total : 0;
            originsJob.percent   = (int32)(percent > 99 ? 99 : percent);
        }

        // The table, then the signature.
        table[4]     = 'v';
        table[5]     = '5';
        table[6]     = (uint8)(entries & 0xFF);
        table[7]     = (uint8)(entries >> 8);
        size_t entry = 0;
        for (const PlannedWave &planned : plan) {
            for (const std::string &name : planned.paths) {
                uint8 *at = table.data() + 8 + entry++ * 24;
                PathKey(name, at);
                PutU32(at + 16, (uint32)planned.offset);
                PutU32(at + 20, planned.size & 0x7FFFFFFF); // Unencrypted.
            }
        }
        if (fseek(out.file, 4, SEEK_SET) != 0 || fwrite(table.data() + 4, 1, table.size() - 4, out.file) != table.size() - 4
            || fflush(out.file) != 0 || fseek(out.file, 0, SEEK_SET) != 0 || fwrite("RSDK", 1, 4, out.file) != 4 || fflush(out.file) != 0) {
            *error = "cannot write " + OriginsAudioPackName(game.id) + " (disk full?)";
            return false;
        }
    }
    return true;
}

/** The conversion thread's work. */
void RunOriginsConversion()
{
    // The bytes to read, for the progress (sound files are counted whole).
    uint64 total = 0;
    bool any     = false;
    for (const OriginsAudioFile &file : kOriginsAudioFiles) {
        const std::string path = FindOriginsFile(std::string(file.name) + (file.streamed ? ".awb" : ".acb"), nullptr);
        PackFile data(path, "rb");
        if (data.file)
            total += (uint64)FileSizeOf(data.file);
        any = any || !FindOriginsFile(std::string(file.name) + ".acb", nullptr).empty();
    }
    if (!any) {
        SetOriginsMessage("No files found: copy the .acb and .awb files from Sonic Origins' image/x64/raw/sound folder into "
                          "the \"origins\" folder next to the retro packs.");
        originsJob.running  = false;
        originsJob.finished = true;
        return;
    }

    uint64 done = 0;
    std::string summary, failures;
    for (const OriginsGame &game : OriginsGames()) {
        if (originsJob.cancel)
            break;
        std::string title = game.id;
        for (const GameInfo &info : kRetroGames) {
            if (!strcmp(info.id, game.id))
                title = info.title;
        }
        SetOriginsMessage("Converting " + title + "...");
        int32 written = 0;
        std::string error;
        if (ConvertOriginsGame(game, &done, total, &written, &error))
            summary += (summary.empty() ? "" : ", ") + title + " (" + std::to_string(written) + " sounds)";
        else if (error != "no files")
            failures += (failures.empty() ? "" : "; ") + title + ": " + error;
    }

    std::string text = summary.empty() ? "Nothing converted." : "Converted " + summary + ".";
    if (!failures.empty())
        text += " Failed: " + failures + ".";
    SetOriginsMessage(text);
    originsJob.percent  = 100;
    originsJob.running  = false;
    originsJob.finished = true;
}

/** Starts the conversion on its own thread. @return False if one is already running. */
bool StartOriginsConversion()
{
    // The menu (engine thread) and a port's page (its own thread) may both ask.
    static std::mutex starting;
    std::lock_guard<std::mutex> guard(starting);
    if (originsJob.running)
        return false;
    if (originsJob.worker.joinable())
        originsJob.worker.join();
    originsJob.cancel   = false;
    originsJob.finished = false;
    originsJob.percent  = 0;
    originsJob.running  = true;
    SetOriginsMessage("Starting...");
    originsJob.worker = std::thread(RunOriginsConversion);
    return true;
}

/** Stops a running conversion and waits for its thread (at shutdown). */
void StopOriginsConversion()
{
    originsJob.cancel = true;
    if (originsJob.worker.joinable())
        originsJob.worker.join();
}

/** The last message (progress or result). */
std::string OriginsMessage()
{
    std::lock_guard<std::mutex> guard(originsJob.lock);
    return originsJob.message;
}

/**
 * A game's converted pack: in the user folder's "retro" folder, else in the
 * first added folder that has it. Its path is relative to the user folder or
 * absolute, as LoadDataPack() takes it.
 */
Pack FindOriginsAudioPack(const char *gameId)
{
    std::vector<std::string> candidates = { std::string(kRetroFolder) + "/" + OriginsAudioPackName(gameId) };
    for (const std::string &folder : extraPackFolders) candidates.push_back(folder + OriginsAudioPackName(gameId));
    Pack pack;
    for (const std::string &candidate : candidates) {
        PackFile file(UserPath(candidate), "rb");
        uint8 header[6] = {};
        // The signature is written last: an interrupted conversion's pack has none.
        if (!file.file || fread(header, 1, sizeof(header), file.file) != sizeof(header) || memcmp(header, "RSDK", 4) != 0)
            continue;
        pack.state   = PACK_READY;
        pack.path    = candidate;
        pack.version = (char)header[5];
        return pack;
    }
    return pack;
}

