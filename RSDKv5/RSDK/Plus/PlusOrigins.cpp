// =====================
// Plus: Sonic Origins' own audio for the retro games
// =====================
//
// Included by Plus.cpp, after PlusPacks.cpp.
//
// Sonic Origins does not play the retro games' music and sounds through the
// engine: its packs have none, and it plays them with CRIWARE, from .acb/.awb
// files of HCA audio encrypted with one key per file. The player copies those
// files (from Sonic Origins' image/x64/raw/sound folder) into a folder named
// "origins" next to the retro packs, and chooses "Convert Sonic Origins
// audio" (the Plus menu's Settings, or a port's own page): this file then
// writes one data pack per game, "<game>-origins-audio.rsdk" next to the
// "origins" folder, with each sound the game asks for under the name it asks
// for ("Data/SoundFX/Global/Jump.wav", "Data/Music/GreenHill.ogg"), as an HCA
// file without its encryption. The engine plays those (Audio/HcaAudio.hpp).
//
// Which cue each file is comes from Sonic Origins' own table
// (PlusOriginsTable.hpp, generated by tools/make-origins-audio-table.py).
//
// The pack is loaded right after the game's Origins pack, so a sound comes
// from Sonic Origins first, then from the earlier release's pack, then from
// Sonic Mania's (PlusAudio.cpp).
//
// Files read, all CRIWARE formats:
//   - @UTF: a table (big-endian), the format of everything in an .acb;
//   - AFS2: a list of files (an .awb, or an .acb's AwbFile column);
//   - HCA: the audio. Its blocks are encrypted with the file's key, times a
//     "subkey" from the AFS2 header when that is non-zero; which one a file
//     uses is found by test-decoding a few blocks.
//
// The conversion runs on its own thread (it reads up to 400 MB); the engine's
// thread only asks how it is going (OriginsAudioProgress()).

