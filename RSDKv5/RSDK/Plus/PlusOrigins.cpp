// ---------------------
// Big-endian reads within bounds
// ---------------------

/** Bytes of a file in memory, read big-endian with every access checked. */
struct ByteView {
    const uint8 *data = nullptr;
    size_t size       = 0;

    bool Has(size_t offset, size_t count) const { return offset <= size && count <= size - offset; }
    uint64 Be(size_t offset, size_t count) const
    {
        uint64 value = 0;
        for (size_t i = 0; i < count; ++i) value = (value << 8) | data[offset + i];
        return value;
    }
};

// ---------------------
// @UTF tables
// ---------------------

/** A value of a table cell. */
struct UtfValue {
    uint64 integer = 0;     ///< Integer columns.
    std::string text;       ///< String columns.
    size_t dataOffset = 0;  ///< Data columns: where, in the file the table is in.
    uint32 dataSize   = 0;
};

/**
 * A CRIWARE @UTF table: "@UTF", u32 size, then (from there, all offsets
 * relative to it) u16 version, u16 rows' offset, u32 strings' offset, u32
 * data's offset, u32 table name, u16 columns, u16 row width, u32 rows; each
 * column a flags byte (storage << 4 | type) and a u32 name, followed by its
 * value when constant; each row the per-row columns' values in order.
 */
class UtfTable
{
public:
    /** Reads the table at @p offset of @p file. @return False if it is not a well-formed table. */
    bool Parse(const ByteView &file, size_t offset)
    {
        view = file;
        if (!file.Has(offset, 32) || memcmp(file.data + offset, "@UTF", 4) != 0)
            return false;
        const uint64 tableSize = file.Be(offset + 4, 4);
        base                   = offset + 8;
        if (!file.Has(base, (size_t)tableSize) || tableSize < 24)
            return false;
        end         = base + (size_t)tableSize;
        rowsOffset  = base + (size_t)file.Be(base + 2, 2);
        strings     = base + (size_t)file.Be(base + 4, 4);
        dataStart   = base + (size_t)file.Be(base + 8, 4);
        const uint32 columnCount = (uint32)file.Be(base + 16, 2);
        rowWidth    = (uint32)file.Be(base + 18, 2);
        rowCount    = (uint32)file.Be(base + 20, 4);
        if (strings > end || dataStart > end || rowsOffset > end || (uint64)rowWidth * rowCount > end - rowsOffset)
            return false;

        size_t pos       = base + 24;
        uint32 rowOffset = 0;
        for (uint32 c = 0; c < columnCount; ++c) {
            if (pos + 5 > end)
                return false;
            Column column;
            const uint8 flags = file.data[pos];
            column.storage    = flags & 0xF0;
            column.type       = flags & 0x0F;
            if (!Text((size_t)file.Be(pos + 1, 4), &column.name))
                return false;
            pos += 5;
            const size_t width = TypeWidth(column.type);
            if (!width)
                return false;
            if (column.storage == 0x30 || column.storage == 0x70) { // Constant.
                if (pos + width > end)
                    return false;
                column.offset = pos;
                pos += width;
            }
            else if (column.storage == 0x50) { // Per row.
                column.offset = rowOffset;
                rowOffset += (uint32)width;
            }
            columns.push_back(column);
        }
        return rowOffset <= rowWidth;
    }

    uint32 Rows() const { return rowCount; }

    /** Cell @p row of column @p name. @return False if there is no such column (or it is empty). */
    bool Get(uint32 row, const char *name, UtfValue *out) const
    {
        for (const Column &column : columns) {
            if (column.name != name)
                continue;
            if (row >= rowCount || column.storage == 0x10 || column.storage == 0)
                return false;
            const size_t at = column.storage == 0x50 ? rowsOffset + (size_t)row * rowWidth + column.offset : column.offset;
            return Read(column.type, at, out);
        }
        return false;
    }

    uint64 Int(uint32 row, const char *name, uint64 fallback = 0) const
    {
        UtfValue value;
        return Get(row, name, &value) ? value.integer : fallback;
    }

    /** A data cell as a view of the file. */
    bool Data(uint32 row, const char *name, ByteView *out) const
    {
        UtfValue value;
        if (!Get(row, name, &value) || !value.dataSize || !view.Has(value.dataOffset, value.dataSize))
            return false;
        out->data = view.data + value.dataOffset;
        out->size = value.dataSize;
        return true;
    }

    /** Where a data cell is in the file (for a table inside it). */
    bool DataOffset(uint32 row, const char *name, size_t *offset) const
    {
        UtfValue value;
        if (!Get(row, name, &value) || !value.dataSize || !view.Has(value.dataOffset, value.dataSize))
            return false;
        *offset = value.dataOffset;
        return true;
    }

private:
    struct Column {
        std::string name;
        uint8 storage = 0;
        uint8 type    = 0;
        size_t offset = 0; ///< In the file (constant) or in the row (per row).
    };

    /** Bytes a value of @p type takes (0 for an unknown type). */
    static size_t TypeWidth(uint8 type)
    {
        static const uint8 widths[] = { 1, 1, 2, 2, 4, 4, 8, 8, 4, 8, 4, 8 };
        return type < sizeof(widths) ? widths[type] : 0;
    }

    bool Text(size_t offset, std::string *out) const
    {
        size_t at = strings + offset;
        if (at >= end)
            return false;
        out->clear();
        while (at < end && view.data[at]) out->push_back((char)view.data[at++]);
        return at < end;
    }

    bool Read(uint8 type, size_t at, UtfValue *out) const
    {
        const size_t width = TypeWidth(type);
        if (at + width > end)
            return false;
        if (type <= 9) { // Integers (floats only as their bits; none are needed here).
            out->integer = view.Be(at, width);
            return true;
        }
        if (type == 0xA)
            return Text((size_t)view.Be(at, 4), &out->text);
        out->dataOffset = dataStart + (size_t)view.Be(at, 4);
        out->dataSize   = (uint32)view.Be(at + 4, 4);
        return out->dataOffset <= end && out->dataSize <= end - out->dataOffset;
    }

    ByteView view;
    size_t base = 0, end = 0, rowsOffset = 0, strings = 0, dataStart = 0;
    uint32 rowWidth = 0, rowCount = 0;
    std::vector<Column> columns;
};

// ---------------------
// AFS2 file lists
// ---------------------

/**
 * An AFS2 list: "AFS2", u8 version, u8 offset size, u8 id size, u8 0, u32
 * count, u16 alignment, u16 subkey, the ids, then count + 1 offsets (each
 * file starts at its offset rounded up to the alignment and ends at the next).
 * Little-endian, unlike @UTF.
 */
struct Afs2List {
    struct Entry {
        uint64 start = 0, end = 0;
    };
    std::map<uint32, Entry> files;
    uint16 subkey = 0;

    /**
     * Reads the list at @p offset through @p read (which reads bytes of the
     * file the list is in, false past its end).
     */
    bool Parse(const std::function<bool(uint64, void *, size_t)> &read, uint64 offset)
    {
        uint8 header[16];
        if (!read(offset, header, sizeof(header)) || memcmp(header, "AFS2", 4) != 0)
            return false;
        const uint32 offsetSize = header[5], idSize = header[6];
        const uint32 count      = header[8] | (header[9] << 8) | (header[10] << 16) | ((uint32)header[11] << 24);
        const uint32 alignment  = header[12] | (header[13] << 8);
        subkey                  = (uint16)(header[14] | (header[15] << 8));
        if (offsetSize < 2 || offsetSize > 8 || (idSize != 2 && idSize != 4) || !alignment || count > 0x100000)
            return false;

        std::vector<uint8> table((size_t)count * idSize + ((size_t)count + 1) * offsetSize);
        if (!read(offset + sizeof(header), table.data(), table.size()))
            return false;
        auto little = [&](size_t at, uint32 width) {
            uint64 value = 0;
            for (uint32 i = 0; i < width; ++i) value |= (uint64)table[at + i] << (8 * i);
            return value;
        };
        const size_t offsets = (size_t)count * idSize;
        for (uint32 i = 0; i < count; ++i) {
            Entry entry;
            entry.start = little(offsets + (size_t)i * offsetSize, offsetSize);
            entry.start = (entry.start + alignment - 1) / alignment * alignment;
            entry.end   = little(offsets + ((size_t)i + 1) * offsetSize, offsetSize);
            if (entry.end < entry.start)
                return false;
            entry.start += offset;
            entry.end += offset;
            files[(uint32)little((size_t)i * idSize, idSize)] = entry;
        }
        return true;
    }
};

// ---------------------
// .acb (and .awb) files
// ---------------------

/** A sound's audio in an .acb: in its own AwbFile, or in the .awb next to it. */
struct AcbWave {
    bool streamed = false;
    uint32 id     = 0;
};

/**
 * An .acb: its header table names the tables used here. A cue (CueNameTable
 * -> CueTable) refers to a waveform, a synth or a sequence; a sequence's
 * tracks (TrackTable) hold events (TrackEventTable) whose "note on" command
 * (2000) names a synth; a synth's ReferenceItems name a waveform, or
 * another synth or sequence; a waveform (WaveformTable) says where its audio is.
 */
class AcbFile
{
public:
    /** Opens @p acbPath (read whole: the largest is 10 MB) and, if @p awbPath is not empty, its .awb. */
    bool Open(const std::string &acbPath, const std::string &awbPath, uint64 fileKey)
    {
        key = fileKey;
        PackFile acb(acbPath, "rb");
        if (!acb.file)
            return false;
        const int64 size = FileSizeOf(acb.file);
        if (size <= 0 || size > 64 * 1024 * 1024)
            return false;
        bytes.resize((size_t)size);
        if (fread(bytes.data(), 1, bytes.size(), acb.file) != bytes.size())
            return false;
        view = { bytes.data(), bytes.size() };

        UtfTable header;
        if (!header.Parse(view, 0) || !header.Rows())
            return false;
        auto table = [&](const char *name, UtfTable *out) {
            size_t offset = 0;
            return header.DataOffset(0, name, &offset) && out->Parse(view, offset);
        };
        if (!table("CueNameTable", &cueNames) || !table("CueTable", &cues) || !table("WaveformTable", &waves))
            return false;
        table("SynthTable", &synths);
        table("SequenceTable", &sequences);
        table("TrackTable", &tracks);
        table("TrackEventTable", &events);

        size_t memoryAwb = 0;
        if (header.DataOffset(0, "AwbFile", &memoryAwb)) {
            auto read = [this](uint64 at, void *out, size_t count) {
                if (!view.Has((size_t)at, count))
                    return false;
                memcpy(out, view.data + at, count);
                return true;
            };
            if (!memory.Parse(read, memoryAwb))
                return false;
        }

        if (!awbPath.empty()) {
            awb.reset(new PackFile(awbPath, "rb"));
            if (!awb->file)
                return false;
            FILE *file = awb->file;
            auto read  = [file](uint64 at, void *out, size_t count) {
                return fseek(file, (long)at, SEEK_SET) == 0 && fread(out, 1, count, file) == count;
            };
            if (!streamed.Parse(read, 0))
                return false;
        }
        return true;
    }

    /** The waveform cue @p name plays. */
    bool FindCue(const std::string &name, AcbWave *out) const
    {
        for (uint32 row = 0; row < cueNames.Rows(); ++row) {
            UtfValue value;
            if (!cueNames.Get(row, "CueName", &value) || value.text != name)
                continue;
            const uint32 cue = (uint32)cueNames.Int(row, "CueIndex", 0xFFFFFFFF);
            if (cue >= cues.Rows())
                return false;
            const uint32 type  = (uint32)cues.Int(cue, "ReferenceType");
            const uint32 index = (uint32)cues.Int(cue, "ReferenceIndex");
            return Reference(type, index, 0, out);
        }
        return false;
    }

    /** The audio of @p wave (an HCA file, still encrypted). */
    bool ReadWave(const AcbWave &wave, std::vector<uint8> *out) const
    {
        const Afs2List &list = wave.streamed ? streamed : memory;
        auto entry           = list.files.find(wave.id);
        if (entry == list.files.end() || entry->second.end - entry->second.start > 64 * 1024 * 1024)
            return false;
        out->resize((size_t)(entry->second.end - entry->second.start));
        if (!wave.streamed) {
            if (!view.Has((size_t)entry->second.start, out->size()))
                return false;
            memcpy(out->data(), view.data + entry->second.start, out->size());
            return true;
        }
        return fseek(awb->file, (long)entry->second.start, SEEK_SET) == 0 && fread(out->data(), 1, out->size(), awb->file) == out->size();
    }

    /** Bytes @p wave's audio takes (for the progress). */
    uint64 WaveSize(const AcbWave &wave) const
    {
        const Afs2List &list = wave.streamed ? streamed : memory;
        auto entry           = list.files.find(wave.id);
        return entry == list.files.end() ? 0 : entry->second.end - entry->second.start;
    }

    /** The key for @p wave's file, without and with the subkey of the list it is in. */
    uint64 Key() const { return key; }
    uint16 Subkey(const AcbWave &wave) const { return wave.streamed ? streamed.subkey : memory.subkey; }

private:
    /** Follows reference @p type (1 waveform, 2 synth, 3 sequence) @p index to a waveform. */
    bool Reference(uint32 type, uint32 index, int32 depth, AcbWave *out) const
    {
        if (depth > 8)
            return false; // A loop in a damaged file.
        if (type == 1)
            return Waveform(index, out);
        if (type == 2)
            return Synth(index, depth + 1, out);
        if (type == 3)
            return Sequence(index, depth + 1, out);
        return false;
    }

    bool Waveform(uint32 index, AcbWave *out) const
    {
        if (index >= waves.Rows())
            return false;
        // Streaming: 0 in the .acb, 1 in the .awb, 2 both (the .awb has all of it).
        out->streamed = waves.Int(index, "Streaming") != 0;
        out->id       = (uint32)waves.Int(index, out->streamed ? "StreamAwbId" : "MemoryAwbId", 0xFFFF);
        if (out->streamed && !awb)
            return false;
        // Older .acb files have a single "Id" column.
        if (out->id == 0xFFFF)
            out->id = (uint32)waves.Int(index, "Id", 0xFFFF);
        return out->id != 0xFFFF;
    }

    bool Synth(uint32 index, int32 depth, AcbWave *out) const
    {
        ByteView items;
        if (index >= synths.Rows() || !synths.Data(index, "ReferenceItems", &items))
            return false;
        // (u16 type, u16 index) pairs; a random or sequential synth plays one of them: the first.
        for (size_t at = 0; at + 4 <= items.size; at += 4) {
            if (Reference((uint32)items.Be(at, 2), (uint32)items.Be(at + 2, 2), depth, out))
                return true;
        }
        return false;
    }

    bool Sequence(uint32 index, int32 depth, AcbWave *out) const
    {
        ByteView trackList;
        if (index >= sequences.Rows() || !sequences.Data(index, "TrackIndex", &trackList))
            return false;
        for (size_t t = 0; t + 2 <= trackList.size; t += 2) {
            const uint32 track = (uint32)trackList.Be(t, 2);
            const uint32 event = (uint32)tracks.Int(track, "EventIndex", 0xFFFF);
            ByteView commands;
            if (track >= tracks.Rows() || event >= events.Rows() || !events.Data(event, "Command", &commands))
                continue;
            // Commands: u16 code, u8 size, then size bytes. 2000 and 2003 play a (u16 type, u16 index).
            for (size_t at = 0; at + 3 <= commands.size;) {
                const uint32 code = (uint32)commands.Be(at, 2);
                const uint32 size = commands.data[at + 2];
                if (at + 3 + size > commands.size)
                    break;
                if ((code == 2000 || code == 2003) && size >= 4
                    && Reference((uint32)commands.Be(at + 3, 2), (uint32)commands.Be(at + 5, 2), depth, out))
                    return true;
                at += 3 + size;
            }
        }
        return false;
    }

    std::vector<uint8> bytes;
    ByteView view;
    uint64 key = 0;
    UtfTable cueNames, cues, synths, sequences, tracks, events, waves;
    Afs2List memory, streamed;
    std::unique_ptr<PackFile> awb;
};

